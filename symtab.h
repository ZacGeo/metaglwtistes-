#ifndef SYMTAB_H
#define SYMTAB_H

/* ============================================================
   symtab.h  —  Πίνακας Συμβόλων για μεταγλωττιστή CPP
   API συμβατό με parser.y
   ============================================================ */

/* Αρχικοποίηση — καλείται μια φορά στην αρχή */
void symtab_init(void);

/* Κλείνει όλες τις ανοιχτές εμβέλειες και τυπώνει τα περιεχόμενα */
void symtab_finish(void);

/* ── Διαχείριση εμβελειών ── */
void symtab_enter_scope(const char *label);   /* νέα εμβέλεια            */
void symtab_leave_scope(void);                /* κλείνουμε την τρέχουσα  */

/* ── Δήλωση αναγνωριστικού στην τρέχουσα εμβέλεια ──
   Το name είναι strdup'd — η symtab ΔΕΝ το free-άρει.
   Επιστρέφει 0 αν OK, -1 αν υπάρχει ήδη (διπλή δήλωση). */
int symtab_declare(const char *name);

/* Αναζήτηση σε όλη την αλυσίδα εμβελειών.
   Επιστρέφει 1 αν βρέθηκε, 0 αν όχι. */
int symtab_lookup(const char *name);

#endif /* SYMTAB_H */
